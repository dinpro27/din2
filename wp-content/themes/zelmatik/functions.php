/**
 * Title filter 
 */
function mediamaven_filter_wp_title( $old_title, $sep, $sep_location ){

	$site_name = get_bloginfo( 'name' );
	$site_description = get_bloginfo( 'description' );
	// add padding to the sep
	$ssep = ' ' . $sep . ' ';
	
	if ( $site_description && ( is_home() || is_front_page() ) ) {
		return $site_name . ' | ' . $site_description;
	} else {
		// find the type of index page this is
		if( is_category() ) $insert = $ssep . __( 'Category', 'media-maven' );
		elseif( is_tag() ) $insert = $ssep . __( 'Tag', 'media-maven' );
		elseif( is_author() ) $insert = $ssep . __( 'Author', 'media-maven' );
		elseif( is_year() || is_month() || is_day() ) $insert = $ssep . __( 'Archives', 'media-maven' );
		else $insert = NULL;
		 
		// get the page number we're on (index)
		if( get_query_var( 'paged' ) )
		$num = $ssep . __( 'Page ', 'media-maven' ) . get_query_var( 'paged' );
		 
		// get the page number we're on (multipage post)
		elseif( get_query_var( 'page' ) )
		$num = $ssep . __( 'Page ', 'media-maven' ) . get_query_var( 'page' );
		 
		// else
		else $num = NULL;
		 
		// concoct and return new title
		return $site_name . $insert . $old_title . $num;
		
	}

}

